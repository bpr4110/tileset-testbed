"""Generate the original and optimized tilesets."""

from __future__ import annotations

from pathlib import Path

from .colors import make_palette
from .glb import build_optimized_glb, build_original_glb, write_glb
from .layouts import Anchor, Layout
from .shapes import Shape, make_shape
from .tileset import bounds_to_box, write_tileset


def _format_params(
    layout: Layout, shape: Shape, size: float, gap: float, anchor: Anchor
) -> str:
    rows = [
        ("layout", layout.name),
        ("shape", shape.value),
        ("colors", layout.colors),
        ("size", size),
        ("gap", gap),
        ("anchor", anchor.value),
        *layout.params,
    ]
    return "\n".join(f"| `{name}` | `{value}` |" for name, value in rows)


def write_readme(
    output: Path,
    layout: Layout,
    shape: Shape,
    size: float,
    gap: float,
    anchor: Anchor,
) -> None:
    if layout.grouped:
        original_description = (
            "One node/mesh/material per color, with every shape of that color\n"
            "  baked into the color's group mesh."
        )
    else:
        original_description = (
            "One single-shape mesh per color and one node per shape. This keeps\n"
            "  the file compact for non-grid layouts, at the cost of many nodes."
        )

    text = f"""# Generated tilesets

Generated by `tileset-testbed`.

| argument | value |
| --- | --- |
{_format_params(layout, shape, size, gap, anchor)}

Total shapes: **{layout.total}** ({layout.colors} colors).

## Files

- `original/tileset.json` + `original/content.glb`
  {original_description}
- `optimized/tileset.json` + `optimized/content.glb`
  One {shape.value} mesh, one white material, and one node with
  `{layout.total}` {shape.value} instance(s). Per-instance colors are stored as
  feature IDs plus an `EXT_structural_metadata` property table.

The optimized GLB can be slightly larger than the original for very small
scenes because of the metadata and instance tables. The runtime saving is in
components and draw calls.

## Cesium for Unreal setup for the optimized tileset

The optimized tileset renders with the shared white material until a
metadata-aware material is assigned:

1. Add a `Cesium Features Metadata` component to the `Cesium3DTileset` actor.
2. Click **Auto Fill**.
3. In the feature ID sets, keep the instance set whose name is
   `instanceColor` (or `_FEATURE_INSTANCE_ID_0`).
4. In the property tables, keep `instanceColorTable` and its `baseColor`
   property. Set its encoding to **Vec4 / Float / Coerce** (not Uint8).
5. Click **Generate Material**.
6. Duplicate or derive a Material from `M_CesiumBaseMaterial`, add the
   generated material layer to that Material's layer stack, and rename the
   layer to exactly `FeaturesMetadata`. Then create a Material Instance from
   that Material.
7. In the generated layer, wire the `baseColor` output of
   `Get Property Values From instanceColorTable` into Base Color. The plugin
   binds the property texture as `PTABLE_instanceColorTable_baseColor`.
8. Assign the Material Instance to the tileset's **Material** slot and refresh
   the tileset (refresh again after changing the component description).

## Notes

- No georeferencing transform is written: `root.transform` is identity.
  In Cesium for Unreal this places the content at the ECEF origin unless you
  place or transform the tileset yourself.
- The optimized GLB is intentionally not self-styling. A generic glTF viewer
  will render the shared white material; the per-instance colors only appear
  after the material setup above.
- The original GLB uses linear `baseColorFactor` values, so any color-managed
  glTF viewer shows the intended palette.
"""
    (output / "README.md").write_text(text, encoding="utf-8")


def generate(
    layout: Layout,
    shape: Shape,
    size: float,
    gap: float,
    output: Path,
    anchor: Anchor = Anchor.auto,
    force: bool = False,
) -> dict[str, Path]:
    """Write both tilesets and return their paths."""
    shape_mesh = make_shape(shape, size)

    effective_anchor = layout.default_anchor if anchor is Anchor.auto else anchor
    shape_min, shape_max = shape_mesh.bounds()
    if effective_anchor is Anchor.center:
        center = tuple((shape_min[axis] + shape_max[axis]) / 2.0 for axis in range(3))
        layout = layout.translated((-center[0], -center[1], -center[2]))

    # Shift the entire scene so its lowest shape touches Y = 0.
    min_y = layout.bounds(shape_mesh)[0][1]
    layout = layout.translated((0.0, -min_y, 0.0))

    box, radius = bounds_to_box(*layout.bounds(shape_mesh))

    output = output.expanduser().resolve()
    if output.exists() and not output.is_dir():
        raise ValueError(f"output path is not a directory: {output}")

    if output.exists() and not force:
        collisions = [
            path
            for path in (
                output / "original" / "tileset.json",
                output / "original" / "content.glb",
                output / "optimized" / "tileset.json",
                output / "optimized" / "content.glb",
                output / "README.md",
            )
            if path.exists()
        ]
        if collisions:
            raise FileExistsError(
                f"output already contains generated files ({collisions[0]}); "
                "pass --force to overwrite"
            )

    original_dir = output / "original"
    optimized_dir = output / "optimized"
    original_dir.mkdir(parents=True, exist_ok=True)
    optimized_dir.mkdir(parents=True, exist_ok=True)

    palette = make_palette(layout.colors)

    original_gltf, original_binary = build_original_glb(layout, palette, shape_mesh)
    write_glb(original_dir / "content.glb", original_gltf, original_binary)
    write_tileset(original_dir / "tileset.json", box, radius)

    optimized_gltf, optimized_binary = build_optimized_glb(layout, palette, shape_mesh)
    write_glb(optimized_dir / "content.glb", optimized_gltf, optimized_binary)
    write_tileset(optimized_dir / "tileset.json", box, radius)

    write_readme(output, layout, shape, size, gap, effective_anchor)

    return {
        "original": original_dir / "tileset.json",
        "optimized": optimized_dir / "tileset.json",
        "readme": output / "README.md",
    }
